/* TAGRA version selector v1.1 (9. 11. 2026: DE pages link to the German shop /de/) | v1.0 (7. 11. 2026) – tagra.app
   Progressive enhancement of the static selector markup generated by tools/tagra-selector.mjs.
   Without JS every option is a plain link to the exact shop.tagra.app product (HU: inquiry with Rukon Kft.).
   With JS the choice updates the recommendation in place (price excl. VAT + CTA to the exact product).
   Prices come only from window.TAGRA_PRICES (assets/js/tagra-prices.js), shared with shop-fleet.js.
   Types: data-tsel="fleet" (vehicles 1 / 2 / 3–4 / 5–6 / 7+, optional download device row)
          data-tsel="driver" (1 driver = TAGRA TRUCKER, 2 drivers in a pair = TAGRA TRUCKER 2).
   All texts live in data-* attributes of the markup, so this file is language independent.
   GA4 (gtag, 8. 11. 2026 – F10; dřív dataLayer.push, který gtag.js bez GTM ignoroval):
     fleet_selector_change {from,to,selector,page_path} · fleet_selector_cta {product,selector,page_path}
     HU (data-base = poptávka u Rukon Kft., /hu/kapcsolat/ nemá formulář): navíc contact_click
     {channel:'rukon_inquiry', product} — stejný event jako e-mail/telefon, ne generate_lead. */
(function(){
  'use strict';
  if(window.tgSelector)return;
  window.tgSelector=true;
  var P=window.TAGRA_PRICES;
  if(!P||!P.tiers)return; /* static links keep working */

  var tiers={},state={fleet:{k:'t1',dev:'none'},driver:{k:'tr1'}};
  P.tiers.forEach(function(t){tiers[t.id]=t;});
  tiers.tr1=P.trucker;tiers.tr2=P.trucker2;

  function track(name,o,beacon){
    if(typeof window.gtag!=='function')return;   /* Consent Mode v2 – gtag si souhlas hlídá sám */
    o.page_path=location.pathname;
    o.page_language=(document.documentElement.getAttribute('lang')||'').slice(0,2).toLowerCase();
    if(beacon)o.transport_type='beacon';
    try{window.gtag('event',name,o);}catch(e){}
  }
  function fmt(el,n){
    var s=(Math.round(n*100)%100===0)?String(Math.round(n)):n.toFixed(2);
    s=s.replace('.',el.getAttribute('data-dec')||'.');
    return (el.getAttribute('data-fmt')||'€{n}').replace('{n}',s);
  }
  var SHOPL={de:'/de'};   /* languages that have their own shop.tagra.app version – add 'xx':'/xx' when it goes live */
  function fill(tpl,o){return String(tpl||'').replace(/\{(\w+)\}/g,function(m,k){return o.hasOwnProperty(k)?o[k]:m;});}
  /* product key (analytics id) and link for a choice */
  function key(type,k,dev){var t=tiers[k];if(!t)return '';return (type==='fleet'&&dev==='box')?t.bundle.key:t.key;}
  function href(el,type,k,dev){
    var t=tiers[k],base=el.getAttribute('data-base');
    if(base)return base+key(type,k,dev);                       /* HU: inquiry with Rukon */
    var sl=SHOPL[(document.documentElement.getAttribute('lang')||'').slice(0,2).toLowerCase()]||'';   /* shop language version (9. 11. 2026: DE live at /de/) */
    if(t.href&&!sl)return t.href;                                /* TRUCKER 2: /go/tagra-trucker-2/ (one line in _redirects) */
    return P.shop+sl+((type==='fleet'&&dev==='box')?t.bundle.path:t.path);
  }

  /* download device only counts where the instance shows the device row (the hero shows vehicles only) */
  function dev(el){return el.getAttribute('data-tsel')==='fleet'&&el.querySelector('[data-dev]')&&state.fleet.dev==='box'?'box':'none';}
  function render(el){
    var type=el.getAttribute('data-tsel'),s=state[type];if(!s)return;
    var t=tiers[s.k];if(!t)return;
    var box=dev(el)==='box';
    var name=box?t.name+' + '+P.box.name:t.name;
    var price=box?t.bundle.price:t.price;
    [].forEach.call(el.querySelectorAll('.tsel__o[data-k]'),function(o){
      var k=o.getAttribute('data-k'),on=k===s.k;
      o.classList.toggle('is-on',on);
      if(on)o.setAttribute('aria-current','true');else o.removeAttribute('aria-current');
      o.href=href(el,type,k,box?'box':'none');
    });
    [].forEach.call(el.querySelectorAll('.tsel__o[data-dev]'),function(o){
      var d=o.getAttribute('data-dev'),on=d===(box?'box':'none');
      o.classList.toggle('is-on',on);
      if(on)o.setAttribute('aria-current','true');else o.removeAttribute('aria-current');
      o.href=href(el,type,s.k,d);
      var sm=o.querySelector('small[data-save]');
      if(sm&&t.bundle)sm.textContent=fill(sm.getAttribute('data-save'),{save:fmt(el,t.price+P.box.price-t.bundle.price)});
    });
    var cur=el.querySelector('.tsel__o.is-on[data-k]'),q=function(c){return el.querySelector(c);};
    if(q('.tsel__name'))q('.tsel__name').textContent=name;
    if(q('.tsel__cap')&&cur)q('.tsel__cap').textContent=cur.getAttribute('data-cap')||'';
    if(q('.tsel__amt'))q('.tsel__amt').textContent=fmt(el,price);
    if(q('.tsel__fee'))q('.tsel__fee').textContent=fill(el.getAttribute('data-fee'),{fee:fmt(el,t.fee)});
    var note=q('.tsel__note');
    if(note){var nt=box?el.getAttribute('data-note-box'):(cur&&cur.getAttribute('data-note'));note.textContent=nt?fill(nt,{ship:fmt(el,P.shipping)}):'';note.hidden=!nt;}
    var cta=q('.tsel__cta');
    if(cta){cta.href=href(el,type,s.k,box?'box':'none');cta.textContent=fill(el.getAttribute('data-cta'),{name:name});
      cta.setAttribute('data-product',key(type,s.k,box?'box':'none'));}
  }
  function renderAll(type){[].forEach.call(document.querySelectorAll('.tsel[data-tsel="'+type+'"]'),render);}

  function init(){
    var els=document.querySelectorAll('.tsel[data-tsel]');if(!els.length)return;
    [].forEach.call(els,function(el){
      var type=el.getAttribute('data-tsel');if(!state[type])return;
      el.classList.add('tsel--js');
      el.addEventListener('click',function(e){
        var a=e.target.closest&&e.target.closest('a');if(!a||!el.contains(a))return;
        if(a.classList.contains('tsel__cta')){
          var pr=a.getAttribute('data-product')||'';
          track('fleet_selector_cta',{product:pr,selector:type},true);
          if(el.getAttribute('data-base'))track('contact_click',{channel:'rukon_inquiry',product:pr,selector:type},true);
          return;}
        if(!a.classList.contains('tsel__o')||e.ctrlKey||e.metaKey||e.shiftKey||e.button)return;
        e.preventDefault();
        var s=state[type],from=key(type,s.k,dev(el));
        if(a.hasAttribute('data-k'))s.k=a.getAttribute('data-k');
        if(a.hasAttribute('data-dev'))s.dev=a.getAttribute('data-dev');
        var to=key(type,s.k,dev(el));
        renderAll(type);
        if(from!==to)track('fleet_selector_change',{from:from,to:to,selector:type});
      });
    });
    renderAll('fleet');renderAll('driver');
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
})();
